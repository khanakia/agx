"""Cases that pin every doclint rule, both the lines it must flag and the
lines it must leave alone. Run: python3 -m unittest scripts/docs/test_doclint.py
(or `task docs:lint`, which runs these first)."""

import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import doclint


def rules(text, name="page.md", extra=None):
    """Lint text written to a temp folder; return [(line, rule)]."""
    with tempfile.TemporaryDirectory() as d:
        for rel, body in (extra or {}).items():
            p = os.path.join(d, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(body)
        path = os.path.join(d, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        doclint._anchor_cache.clear()
        return [(i + 1, r) for i, r, _ in doclint.lint_file(path)]


class Wrap(unittest.TestCase):
    def test_flags_wrapped_paragraph(self):
        self.assertEqual(rules("One sentence that\nwraps here.\n"), [(2, "wrap")])

    def test_flags_wrapped_list_item_continuation(self):
        self.assertEqual(rules("- an item that\n  carries on indented\n"), [(2, "wrap")])
        self.assertEqual(rules("1. step one that\n   carries on\n"), [(2, "wrap")])

    def test_flags_wrapped_blockquote(self):
        self.assertEqual(rules("> quoted text that\n> carries on\n"), [(2, "wrap")])

    def test_allows_lists_nested_lists_and_blocks(self):
        text = "Intro line:\n- one\n- two\n  - nested\n  1. ordered nested\n3) paren item\n* star\n+ plus\n"
        self.assertEqual(rules(text), [])

    def test_allows_heading_table_fence_html_after_prose(self):
        text = "Text\n## Heading\nText\n| a | b |\n|---|---|\n| 1 | 2 |\nText\n```sh\nline one\nline two\n```\nText\n<img src=\"x.svg\">\n"
        self.assertEqual(rules(text, extra={"x.svg": ""}), [])

    def test_allows_heading_followed_by_paragraph(self):
        self.assertEqual(rules("# Title\nFirst paragraph.\n"), [])

    def test_ignores_code_frontmatter_and_comments(self):
        text = "---\ntitle: x\nother: y\n---\n\n```text\na\nb\n```\n\n<!-- a comment\nthat spans lines -->\n"
        self.assertEqual(rules(text), [])

    def test_quote_after_prose_and_empty_quote_line(self):
        self.assertEqual(rules("Text\n> a quote\n>\n> next quote paragraph\n"), [])

    def test_link_reference_definitions(self):
        self.assertEqual(rules("See [x][1].\n[1]: https://example.com\n[2]: https://example.org\n"), [])


class Links(unittest.TestCase):
    def test_missing_file(self):
        self.assertEqual(rules("See [x](nope.md).\n"), [(1, "link")])

    def test_existing_file_and_dir(self):
        self.assertEqual(rules("See [x](a.md) and [d](sub/).\n", extra={"a.md": "# A\n", "sub/b.md": ""}), [])

    def test_anchor_rules(self):
        target = "# Step 1 — Do `it` now\n## Same\n## Same\n```\n# not a heading\n```\n"
        ok = "[a](t.md#step-1--do-it-now) [b](t.md#same) [c](t.md#same-1)\n"
        self.assertEqual(rules(ok, extra={"t.md": target}), [])
        self.assertEqual(rules("[a](t.md#same-2)\n", extra={"t.md": target}), [(1, "link")])
        self.assertEqual(rules("[a](t.md#not-a-heading)\n", extra={"t.md": target}), [(1, "link")])

    def test_same_page_anchor(self):
        self.assertEqual(rules("# Top\n\n[up](#top) [bad](#nope)\n"), [(3, "link")])

    def test_html_image_and_md_image(self):
        self.assertEqual(rules('<img src="gone.svg" alt="x">\n'), [(1, "link")])
        self.assertEqual(rules("![x](gone.png)\n"), [(1, "link")])

    def test_ignores_urls_and_code(self):
        self.assertEqual(rules("[x](https://example.com/a.md) `[y](nope.md)` [m](mailto:a@b.c)\n\n```\n[z](nope.md)\n```\n"), [])

    def test_line_anchor_on_source_file(self):
        self.assertEqual(rules("[f](main.go#L10) [g](main.go#func)\n", extra={"main.go": ""}), [(1, "link")])


class Paths(unittest.TestCase):
    def test_flags_local_paths_even_in_fences(self):
        for p in ["/Users/x/a", "/Volumes/D/a", "/space/projects/a", "/private/tmp/a", "/khanakia/x", "/home/alice/a"]:
            with self.subTest(p=p):
                self.assertEqual(rules(f"```\ncat {p}\n```\n"), [(2, "path")])

    def test_allows_placeholders_and_urls(self):
        self.assertEqual(rules("~/.agx and /home/you/.claude and /home/demo/x and https://github.com/khanakia/agx and /tmp/x\n"), [])


class Words(unittest.TestCase):
    def test_flags(self):
        for line in [
            "Built for AI agents.",
            "Anthropic ships Claude Code.",
            "Co-Authored-By: someone",
            "This page was generated by a model.",
            "Written with Claude.",
            "Docs created using a language model.",
        ]:
            with self.subTest(line=line):
                self.assertEqual(rules(line + "\n"), [(1, "word")])

    def test_allows(self):
        text = "\n\n".join([
            "agx launches Claude Code and Codex.",
            "The generated shell code calls `command agx`.",
            "Set ANTHROPIC_API_KEY or read anthropic-ratelimit-unified-5h-reset.",
            "A custom-title wins over the ai-title.",
            "Regenerated by agx shell-init on every start.",
        ])
        self.assertEqual(rules(text + "\n"), [])


if __name__ == "__main__":
    unittest.main()
